// Hand-written splitter for the o200k-style pre-tokenizer regex Inkling-2-Mini's tokenizer.json declares:
//
//   [^\r\n\p{L}\p{N}]?[\p{Lu}\p{Lt}\p{Lm}\p{Lo}\p{M}]*[\p{Ll}\p{Lm}\p{Lo}\p{M}]+(?i:'s|'t|'re|'ve|'m|'ll|'d)?
//   |[^\r\n\p{L}\p{N}]?[\p{Lu}\p{Lt}\p{Lm}\p{Lo}\p{M}]+[\p{Ll}\p{Lm}\p{Lo}\p{M}]*(?i:'s|'t|'re|'ve|'m|'ll|'d)?
//   |\p{N}{1,3}| ?[^\s\p{L}\p{N}]+[\r\n/]*|\s*[\r\n]+|\s+(?!\S)|\s+
//
// (one line in tokenizer.json). Note the `[\r\n/]*` tail of the symbol branch: stock o200k_base has `[\r\n]*`.
// The vendored llama.cpp unicode code has no splitter for this pattern and its category flags cannot tell
// Lu/Lt/Ll/Lm/Lo apart, so this file carries its own exact category table (o200k_cats.inc, generated by
// tools/tok_ref/gen_o200k_cats.py) and implements the regex's backtracking semantics directly.
#pragma once

#include <cstddef>
#include <cstdint>
#include <string>
#include <vector>

namespace r4dx {

// The pattern string exactly as tokenizer.json spells it.
extern const char* const kO200kInkling2Regex;

// Splits `cpts` into pre-tokens; returns their lengths in code points (they sum to cpts.size()).
std::vector<size_t> o200k_split_lengths(const std::vector<uint32_t>& cpts);

// Pre-tokenizes UTF-8 `text` (invalid bytes become U+FFFD, like unicode_cpts_from_utf8) and returns each
// pre-token already GPT-2 byte-encoded (what ByteLevel(use_regex=false) hands the BPE).
std::vector<std::string> o200k_split_byte_encoded(const std::string& text);

}  // namespace r4dx
