#!/usr/bin/env python
"""Generates src/tokenizer/o200k_cats.inc: the Unicode category table the o200k pre-tokenizer splitter
(src/tokenizer/o200k_split.cpp) classifies code points with.

The vendored llama.cpp tables only carry a coarse L / M / N / lowercase / uppercase flag set, which cannot
separate Lu / Lt / Ll / Lm / Lo exactly (the Inkling-2 regex puts Lm, Lo and M in BOTH of its letter
classes, Lt only in the "upper" one, Ll only in the "lower" one). This table is exact.

Bits per code point: 1 Lu, 2 Ll, 4 Lt, 8 Lm, 16 Lo, 32 M (Mn|Mc|Me), 64 N (Nd|Nl|No), 128 White_Space
(the Oniguruma / Rust `regex` `\\s` set). Written as (first_cp, bits) run starts; the last run extends to
0x10FFFF. Unicode version = the running Python's `unicodedata.unidata_version`.

CPU only; run with the reference venv, -I:
    D:\\venvs\\r4dx-inkling-ref\\Scripts\\python.exe -I tools\\tok_ref\\gen_o200k_cats.py
"""
import os
import sys
import unicodedata

BITS = {"Lu": 1, "Ll": 2, "Lt": 4, "Lm": 8, "Lo": 16, "Mn": 32, "Mc": 32, "Me": 32, "Nd": 64, "Nl": 64, "No": 64}
WS = set(list(range(0x09, 0x0E)) + [0x20, 0x85, 0xA0, 0x1680] + list(range(0x2000, 0x200B)) +
         [0x2028, 0x2029, 0x202F, 0x205F, 0x3000])


def main():
    out_path = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
                            "src", "tokenizer", "o200k_cats.inc")
    runs = []
    prev = None
    for cp in range(0x110000):
        b = BITS.get(unicodedata.category(chr(cp)), 0)
        if cp in WS:
            b |= 128
        if b != prev:
            runs.append((cp, b))
            prev = b
    lines = ["// Generated by tools/tok_ref/gen_o200k_cats.py -- do not edit.",
             f"// Unicode {unicodedata.unidata_version}; {len(runs)} runs of (first code point, category bits).",
             "// Bits: 1 Lu, 2 Ll, 4 Lt, 8 Lm, 16 Lo, 32 M, 64 N, 128 White_Space."]
    row = []
    for cp, b in runs:
        row.append(f"{{0x{cp:X},{b}}}")
        if len(row) == 10:
            lines.append(",".join(row) + ",")
            row = []
    if row:
        lines.append(",".join(row) + ",")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out_path}: {len(runs)} runs, Unicode {unicodedata.unidata_version}")


if __name__ == "__main__":
    sys.exit(main())
