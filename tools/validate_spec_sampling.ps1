#requires -Version 5.1
<#
.SYNOPSIS
  Mandatory end-to-end losslessness gate for SAMPLED speculative decode (docs/sampling.md sections
  9-11, Milestone 6 stage S3 item 2): proves that lifting the temperature<=0 gate on --mtp/--dflash
  produces BYTE-IDENTICAL generated text to plain sampled decode at the SAME seed and sampling
  flags, by SHA-256 of the raw generated bytes -- not a tolerance-bounded diff. Modeled directly on
  tools/validate_dflash.ps1 (same exit-code / non-empty-stdout / pinned --max-ctx handling, same
  reason for each, same "accept a mismatch only through an explicit, logged control" contract -- see
  that script's own comments for the review findings that shaped it), extended with the two axes
  that only exist for sampled decode: a sampling config (temperature/top_k/top_p) and a seed.

.DESCRIPTION
  The losslessness argument (docs/sampling.md design point D, "sample-and-match" rejection
  sampling): a greedy drafter's proposal distribution is a point mass on its drafted token x, so
  drawing y ~ p once and accepting iff y == x is EXACTLY the standard rejection-sampling accept
  rule, and because exactly one draw is consumed per EMITTED token (never per drafted token), the
  emitted sequence for a fixed seed is identical, token for token, to plain sampled decode from the
  same prompt -- PROVIDED the round's own verify pass computed the same row sequential single-row
  decode would have (see the next paragraph for when it does not). This script is the repeatable,
  real-hardware regression gate for that argument: for every (target layout, prompt, sampling
  config, seed) combination, runs r4dx-cli.exe three ways against the same real target container --
  plain (no --mtp/--dflash, the ground truth), `--mtp 3`, and `--dflash <draft> --dflash-k 7` -- and
  compares SHA-256 of each pair's raw stdout.

  KNOWN, DOCUMENTED, NON-BUG divergence mechanism (docs/sampling.md section 9.3, same mechanism
  tools/validate_dflash.ps1 already documents for greedy MTP): a speculative round computes its
  logits in one q_len>1 batched-verify pass whose floating-point reduction order differs from
  single-row sequential decode's, which a greedy argmax usually survives but a CDF walk does not,
  because the same numeric perturbation can move a candidate boundary by ~1e-2 of the distribution's
  mass right where two candidates are nearly tied. At this container's base divergence rate (most
  sampled trajectories diverge from plain decode SOMEWHERE), "a control also diverges from the
  baseline" is true almost by default and has essentially no power to separate the known mechanism
  from a real bug (review finding, 2026-09-21) -- so this script does NOT accept on that basis. On
  any baseline-vs-speculative mismatch it (a) prints a character-level diff position and both texts'
  prefixes, then (b) tries, in order, up to two controls at the SAME seed/prompt/layout/sampling-
  config, and accepts ONLY if a control's hash EXACTLY MATCHES the speculative run's own hash (not
  merely "diverges from baseline" -- matching the mismatched target exactly is the only evidence
  that the SAME mechanism produced the SAME token sequence): a CROSS-FAMILY control first
  (`--dflash` for an `--mtp 3` mismatch, `--mtp 7` for a `--dflash` mismatch), then, if that does not
  match exactly, a SAME-FAMILY "grouping" control that changes only what the verify window contains
  without touching the mismatching family's own bookkeeping (`--mtp 7` in place of `--mtp 3` for an
  `--mtp` mismatch -- same code path, different k, so a real bookkeeping bug cannot be switched off
  by it; a different draft container, `-DflashAlt`, in place of the default draft for a `--dflash`
  mismatch -- same code path, different drafted-token sequence, mirroring
  `tools/validate_dflash.ps1`'s own second-tier grouping control). Only when one of the two controls
  matches the target's hash exactly (still requires -AllowBatchedVerifyDivergence, a human decision,
  not a default) is the row downgraded to WARN; a mismatch neither control reproduces exactly is a
  hard FAILED regardless of the switch, reported honestly rather than downgraded.

.PARAMETER Model
  Path to the real 64-layer target container. Default: the production container matching build\win-hip's w4a16 group,
  read from build\win-hip\CMakeCache.txt (R4DX_W4A16_GROUP) by tools\r4dx_containers.ps1: group 64
  (the default build) -> D:\models\r4dx\qwen38-27b-v6.r4dx, group 128 -> D:\models\r4dx\qwen38-27b-v3.r4dx.

.PARAMETER Dflash
  Path to the DFlash2 draft container to test. Default: the w4a16 draft container matching the same group -- group 64 ->
  D:\models\r4dx\qwen38-27b-dflash2-w4a16-g64.r4dx, group 128 -> D:\models\r4dx\qwen38-27b-dflash2-w4a16.r4dx.

.PARAMETER DflashAlt
  Second-tier "grouping control" draft container (review fix, 2026-09-21), mirroring
  tools/validate_dflash.ps1's own -DflashAlt: used ONLY when a --dflash mismatch's cross-family
  (--mtp 7) control does not match the mismatch's own hash exactly. A different draft container
  drafts a different token sequence through the identical DFlash2 code path (same verify mechanism,
  different verify-window contents), so if switching to it reproduces the ORIGINAL --dflash run's
  own hash, the divergence is pure verify-window grouping, not a dflash-specific bookkeeping bug --
  a bookkeeping/lifecycle bug cannot be switched off by re-quantizing the draft container. Default:
  the mxfp4 draft container (independent of the w4a16 default above).

.PARAMETER Layouts
  Comma-separated TARGET body layouts. Default: w4a16,w4a8,mxfp4 (bf16 excluded, standing
  bf16-retired-from-perf-work rule -- docs/status.md).

.PARAMETER Seeds
  Comma-separated seeds. Default: 1,2 (the task's own ask).

.PARAMETER MaxTokens
  --max-tokens for every generation. Default 48: long enough to exercise several verify rounds at
  k=3/k=7 without making the full matrix (3 layouts x 2 prompts x 3 sampling configs x 2 seeds x 3
  modes = 108 generations) too slow to actually run.

.PARAMETER Quick
  Restricts Layouts to w4a16 only (a fast smoke pass -- CI/pre-flight use, not the mandatory gate).

.PARAMETER AllowBatchedVerifyDivergence
  If set, a mismatch is downgraded from FAILED to WARN IF AND ONLY IF one of the two controls (see
  .DESCRIPTION) at the SAME seed/prompt/layout/sampling-config matches the mismatch's OWN hash
  exactly. A mismatch neither control reproduces exactly is a hard FAILED regardless of this switch.

.PARAMETER Tp
  Tensor parallelism (docs/tp.md P5, gate G12): 1 (default) runs everything on HIP device 1, exactly
  as before this parameter existed. 2 passes `--tp 2` (real mode, both GPUs) to EVERY r4dx-cli run --
  the plain sampled ground truth, both speculative modes and every control alike, so every comparison
  is TP=2 against TP=2 -- and REMOVES HIP_VISIBLE_DEVICES and R4DX_TP_FAULT for the run (both
  restored at the end, from a finally: an error or Ctrl-C restores them too). It refuses to start
  while an r4dx-server is running (docs/tp.md 9.2); after every run it scans that run's stderr for HIP
  error 719 and, 5 s later, checks for a device-0 TDR (tools\tp\tdr_check.ps1, Appendix B N55),
  stopping at the first one (no retry); and on every exit it runs the check once more 30 s after the
  last run. A TDR fails the script (exit 1). An MTP FAILED row at -Tp 2 is ambiguous on its own: the
  known test_mtp CheckSampledRoundsMatchPlain [w4a16] failure (0/18 identical sampled trajectories at
  TP=1, Appendix B N29) is this property -- run the same matrix at -Tp 1 on the same tree before
  blaming TP (Appendix B N80).

.EXAMPLE
  .\tools\validate_spec_sampling.ps1
.EXAMPLE
  .\tools\validate_spec_sampling.ps1 -Quick -AllowBatchedVerifyDivergence
.EXAMPLE
  .\tools\validate_spec_sampling.ps1 -Tp 2 -Layouts w4a16 -AllowBatchedVerifyDivergence
#>
