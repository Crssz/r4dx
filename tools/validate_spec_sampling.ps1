function Get-Sha256Hex([string]$text) {
    $bytes = [System.Text.Encoding]::UTF8.GetBytes($text)
    $sha = [System.Security.Cryptography.SHA256]::Create()
    try {
        return ([System.BitConverter]::ToString($sha.ComputeHash($bytes))).Replace("-", "").ToLowerInvariant()
    } finally {
        $sha.Dispose()
    }
}

# First index (0-based, UTF-16 code unit) at which $a and $b differ, or -1 if one is a prefix of
# the other, or -2 if identical.
function Find-FirstDiff([string]$a, [string]$b) {
    $n = [Math]::Min($a.Length, $b.Length)
    for ($i = 0; $i -lt $n; $i++) {
        if ($a[$i] -ne $b[$i]) { return $i }
    }
    if ($a.Length -eq $b.Length) { return -2 }
    return -1
}

# `mode`: "baseline" (no --mtp/--dflash, plain sampled decode), "mtp" (--mtp 3), "dflash"
# (--dflash $draftPath --dflash-k 7), "control-mtp7" (--mtp 7 -- the cross-family control for a
# --dflash mismatch, AND the same-family "grouping" control for an --mtp mismatch: same code path,
# different k, so it cannot be switched off by a --mtp-specific bookkeeping bug), or "dflash-alt"
# (--dflash $draftPath --dflash-k 7 with `draftPath` overridden to a DIFFERENT draft container --
# the same-family grouping control for a --dflash mismatch, mirroring tools/validate_dflash.ps1's
# own -DflashAlt). Every mode shares the same --temperature/--top-k/--top-p/--seed, so the ONLY
# thing that differs between baseline and a speculative mode is whether/which drafter ran -- exactly
# the comparison the losslessness gate needs.
function Invoke-Generation([string]$layout, [string]$prompt, [int]$maxCtx, [hashtable]$cfg,
                            [int]$seed, [string]$mode, [string]$draftPath = $Dflash) {
    $commonArgs = @(
        "--model", $Model, "--layout", $layout, "--prompt", $prompt,
        "--max-tokens", $MaxTokens, "--max-ctx", $maxCtx,
        "--temperature", $cfg.Temperature, "--top-k", $cfg.TopK, "--top-p", $cfg.TopP,
        "--min-p", $cfg.MinP, "--seed", $seed
    )
    $modeArgs = switch ($mode) {
        "mtp"          { @("--mtp", 3) }
        "dflash"       { @("--dflash", $draftPath, "--dflash-k", 7) }
        "dflash-alt"   { @("--dflash", $draftPath, "--dflash-k", 7) }
        "control-mtp7" { @("--mtp", 7) }
        default        { @() }
    }
    # r4dx-cli.exe writes its load-time/[stats] lines to stderr, not stdout (src/cli/main.cpp) --
    # only stdout carries the generated text this function needs to hash. Same $ErrorActionPreference
    # relaxation as validate_dflash.ps1's own Invoke-Generation, for the identical reason (Windows
    # PowerShell 5.1 turns a redirected-away stderr line from a native exe into a terminating
    # NativeCommandError under "Stop"). `$TpArgs` (-Tp 2): `--tp 2` on every mode alike. stderr goes to
    # $CliErrLog (overwritten per run), which Assert-NoTdrYet scans under -Tp 2.
    $prevPref = $ErrorActionPreference
    $ErrorActionPreference = "Continue"
    try {
        $out = & $Cli @commonArgs @modeArgs @TpArgs 2>$CliErrLog
        $exitCode = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $prevPref
    }
    Assert-NoTdrYet
    $joined = ($out -join "`n")
    if ($exitCode -ne 0) {
        throw "r4dx-cli exited $exitCode (layout=$layout max-ctx=$maxCtx mode=$mode seed=$seed) -- stdout was: $joined"
    }
    if ([string]::IsNullOrWhiteSpace($joined)) {
        throw "r4dx-cli produced empty stdout (layout=$layout max-ctx=$maxCtx mode=$mode seed=$seed) despite " +
              "exit code 0 -- refusing to hash an empty run as if it were a real result"
    }
    return $joined
}

# Runs one baseline-vs-speculative comparison, trying up to two controls on a mismatch.
# `targetMode`: "mtp" or "dflash". `controls`: an ordered array of @{Mode=;Label=;DraftPath=} --
# tried in order, and the row is accepted (WARN) at the FIRST control whose hash matches the
# MISMATCH'S OWN hash exactly (review fix, 2026-09-21: "also diverges from baseline" is not
# evidence at this container's base divergence rate -- only reproducing the SAME token sequence is).
# Tier 1 is always a cross-family control (changes which speculative code path ran, not its
# parameters); tier 2 is a same-family "grouping" control (changes only the verify window's
# contents -- a different k, or a different draft container -- so a real bookkeeping bug in the
# mismatching family's own code cannot be switched off by it).
function Test-OneCombination([string]$layout, [string]$promptLabel, [string]$prompt, [int]$maxCtx,
                              [string]$cfgLabel, [hashtable]$cfg, [int]$seed,
                              [string]$targetMode, [string]$targetLabel, [array]$controls,
                              [string]$baseline, [string]$hashBase) {
    $speculative = Invoke-Generation -layout $layout -prompt $prompt -maxCtx $maxCtx -cfg $cfg -seed $seed -mode $targetMode
    $hashSpec = Get-Sha256Hex $speculative
    $match = ($hashBase -eq $hashSpec)
    $status = "OK"
    $note = ""
    if (-not $match) {
        # Write-Host (not Write-Output) for every diagnostic line in this function: this function's
        # RETURN VALUE is captured by the caller via `$results += Test-OneCombination ...`, and in
        # PowerShell that capture grabs EVERYTHING written to the success/output stream inside the
        # function, not just the final `return` -- a stray `Write-Output` here would silently splice
        # extra string elements into $results alongside the real pscustomobject rows, corrupting the
        # summary table and the failure/warning counts. Write-Host targets the separate Information
        # stream instead: still visible on console and still captured by the caller script's own
        # `*>&1 | Tee-Object` redirection, but invisible to a variable-assignment capture.
        $diffPos = Find-FirstDiff $baseline $speculative
        Write-Host "  MISMATCH ($targetLabel) vs baseline -- first diff at char $diffPos"
        $ctxStart = [Math]::Max(0, $diffPos - 40)
        $ctxLen = 120
        $baseSnip = $baseline.Substring($ctxStart, [Math]::Min($ctxLen, $baseline.Length - $ctxStart))
        $specSnip = $speculative.Substring($ctxStart, [Math]::Min($ctxLen, $speculative.Length - $ctxStart))
        Write-Host "  baseline        around diff: ...$baseSnip..."
        Write-Host "  $targetLabel around diff: ...$specSnip..."
        $resolvedBy = $null
        $notes = @()
        foreach ($ctrl in $controls) {
            if ($ctrl.ContainsKey("SkipIf") -and (& $ctrl.SkipIf)) {
                $notes += "$($ctrl.Label) control skipped ($($ctrl.SkipReason))"
                continue
            }
            Write-Host "  running $($ctrl.Label) control (same seed/prompt/layout/sampling) ..."
            $ctrlArgs = @{ layout = $layout; prompt = $prompt; maxCtx = $maxCtx; cfg = $cfg; seed = $seed; mode = $ctrl.Mode }
            if ($ctrl.ContainsKey("DraftPath")) { $ctrlArgs.draftPath = $ctrl.DraftPath }
            $control = Invoke-Generation @ctrlArgs
            $hashControl = Get-Sha256Hex $control
            $controlDiverges = ($hashControl -ne $hashBase)
            $controlMatchesTarget = ($hashControl -eq $hashSpec)
            if ($controlMatchesTarget) {
                $notes += "$($ctrl.Label) control MATCHES $targetLabel exactly (same mechanism, confirmed)"
                $resolvedBy = $ctrl.Label
                break
            } else {
                $notes += "$($ctrl.Label) control does NOT match $targetLabel" +
                    $(if ($controlDiverges) { " (diverges from baseline too, but a different divergence -- not proof)" } else { " (matches baseline instead -- this control did not reproduce it)" })
            }
        }
        $note = $notes -join "; "
        if ($resolvedBy) {
            if ($AllowBatchedVerifyDivergence) {
                $status = "WARN (resolved by $resolvedBy control -- $note)"
            } else {
                $status = "FAILED ($resolvedBy control confirms batched-verify mechanism -- rerun with -AllowBatchedVerifyDivergence to accept)"
            }
        } else {
            $status = "FAILED (real bug or unresolved -- no control reproduced this mismatch exactly -- $note)"
        }
        Write-Host "  $note"
    } else {
        Write-Host "  OK ($targetLabel matches baseline, $hashBase)"
    }
    return [pscustomobject]@{
        Layout = $layout; Prompt = $promptLabel; Sampling = $cfgLabel; Seed = $seed; Mode = $targetLabel
        BaselineSha256 = $hashBase; ModeSha256 = $hashSpec; Status = $status; Note = $note
    }
}

